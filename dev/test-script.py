# Script studio journey: keep an idea, draft, refine, switch to coach mode, restore a version.
# Usage: node dev/server.mjs &  then  python3 dev/test-script.py
from playwright.sync_api import sync_playwright
OUT = "/tmp/screens"
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1400, "height": 950})
    errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://localhost:4321/#brand"); pg.click("#loadSample")
    pg.click("nav button[data-view=research]"); pg.click("#runIdeas")
    pg.wait_for_selector("#ideasOut .idea", timeout=20000)
    pg.click("#ideasOut .idea >> nth=0 >> [data-act=keep]")
    pg.click("nav button[data-view=plan]"); pg.wait_for_timeout(200)
    pg.screenshot(path=f"{OUT}/s0-plan.png", full_page=True)
    pg.click(".plan-card >> nth=0 >> [data-script]"); pg.wait_for_timeout(300)
    pg.screenshot(path=f"{OUT}/s1-empty.png", full_page=True)
    pg.click("#genDraft"); pg.wait_for_function("document.querySelector('#scriptText').value.length > 50", timeout=10000)
    pg.wait_for_timeout(300)
    pg.screenshot(path=f"{OUT}/s2-draft.png", full_page=True)
    print("checks after draft:", " | ".join(pg.inner_text("#scriptChecks").split("\n")[2:]))
    pg.click("#refineBox [data-refine] >> nth=1"); pg.wait_for_timeout(1500)
    print("versions:", pg.locator("#scriptVersions .version").count())
    pg.click("#modePicker [data-mode=coach]")
    pg.fill("#scriptText", "Most people waste half their week and never notice it happening to them at all.\nAnd that is why time matters.")
    pg.click("#getCoach"); pg.wait_for_selector(".coach-line", timeout=10000); pg.wait_for_timeout(200)
    pg.screenshot(path=f"{OUT}/s3-coach.png", full_page=True)
    pg.click("#scriptVersions [data-restore] >> nth=0"); pg.wait_for_timeout(200)
    pg.click("#scriptBack"); pg.wait_for_timeout(200)
    pg.screenshot(path=f"{OUT}/s4-list.png", full_page=True)
    pg.reload(); pg.wait_for_timeout(300)
    stage = pg.evaluate("JSON.parse(localStorage.getItem('lk2_plan'))[0].stage")
    print("stage after opening script:", stage, "| script saved:", bool(pg.evaluate("JSON.parse(localStorage.getItem('lk2_plan'))[0].script")))
    m = b.new_page(viewport={"width": 390, "height": 844}); m.goto("http://localhost:4321/#script"); m.wait_for_timeout(300)
    m.screenshot(path=f"{OUT}/s5-mobile.png", full_page=True)
    print("errors:", errs or "none"); b.close()
